const assert = require('node:assert/strict');
const {readFileSync}=require('node:fs');
const {runInNewContext}=require('node:vm');
const sandbox={URL,Date,Map,Set};
runInNewContext(readFileSync('./public/domain.js','utf8'),sandbox);
runInNewContext(readFileSync('./public/core.js','utf8'),sandbox);
const C = sandbox.JobCore;
assert.equal(C.demo.length,18);
assert.equal(C.groupJobs(C.demo).length,12);
assert.equal(C.groupJobs(C.demo,false).length,18);
assert.equal(JSON.stringify(C.groupJobs(C.filterJobs(C.demo,{query:'전략기획 서울'})).map(j=>j.company)),JSON.stringify(['온그로브']));
assert.equal(C.filterJobs(C.demo,{region:'원격',experience:'entry'}).length,1);
assert.ok(C.filterJobs(C.demo,{experience:'8+'}).some(j=>j.company==='핀오크'));
assert.equal(C.filterJobs(C.demo,{query:'없는 직무'}).length,0);
assert.ok(C.filterJobs(C.demo,{sources:['wanted']}).every(j=>j.source==='wanted'));
assert.equal(C.sourceForUrl('https://www.wanted.co.kr/wd/123'),'wanted');
assert.equal(C.sourceForUrl('https://www.wanted.co.kr.evil.example/wd/123'),null);
assert.equal(C.sourceForUrl('javascript:alert(1)'),null);
assert.equal(C.sourceForUrl('http://www.saramin.co.kr/'),null);
const base={url:'https://www.saramin.co.kr/zf_user/jobs/relay/view?rec_idx=1',title:'검증용 공고',company:'검증 기업',min:'',max:''};
const personal=C.validateJob(base);
assert.equal(personal.min,null);
assert.equal(personal.max,null);
assert.equal(C.filterJobs([personal],{experience:'entry'}).length,0);
assert.equal(C.filterJobs([{...personal,min:null,max:3}],{experience:'entry'}).length,0);
assert.throws(()=>C.validateJob({...base,min:5,max:2}));
assert.throws(()=>C.validateJob({...base,deadline:'2026-02-30'}));
assert.equal(C.validateJob({...base,min:0,max:0}).min,0);
assert.equal(C.filterJobs([C.validateJob({...base,min:0,max:0})],{experience:'entry'}).length,1);
assert.equal(C.groupJobs([personal,{...personal,id:'personal-other'}]).length,2);
assert.equal(C.sortJobs([{deadline:null,published:'2026-10-13'},{deadline:'2026-10-20',published:'2026-10-12'}],'deadline')[1].deadline,null);
assert.equal(C.escapeHtml('<script>"x"</script>'),'&lt;script&gt;&quot;x&quot;&lt;/script&gt;');
assert.ok(C.demo.every(j=>j.tasks.length===3&&C.sources[j.source]));
console.log('Passed: 24 search, grouping, validation, date and rendering checks.');
